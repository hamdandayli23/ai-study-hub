let deferredInstallPrompt = null;

// 1. Detect if running as standalone app (Laptop Electron or Installed PWA)
function detectStandaloneEnvironment() {
  const isStandalone = 
    window.matchMedia('(display-mode: standalone)').matches ||
    window.navigator.standalone === true ||
    (window.electronAPI && window.electronAPI.isDesktopApp === true);

  if (isStandalone) {
    document.body.classList.add('running-as-app');
    const installBtn = document.getElementById('pwa-install-btn');
    if (installBtn) installBtn.style.display = 'none';
    console.log('AI Study Hub running in standalone native app mode');
  }
}

// 2. Register Service Worker for offline performance
if ('serviceWorker' in navigator) {
  window.addEventListener('load', () => {
    navigator.serviceWorker.register('./sw.js')
      .then((reg) => console.log('ServiceWorker registered:', reg.scope))
      .catch((err) => console.log('ServiceWorker registration error:', err));
  });
}

// 3. Capture PWA beforeinstallprompt event
window.addEventListener('beforeinstallprompt', (e) => {
  e.preventDefault();
  deferredInstallPrompt = e;
  const installBtn = document.getElementById('pwa-install-btn');
  if (installBtn && !document.body.classList.contains('running-as-app')) {
    installBtn.style.display = 'inline-flex';
  }
});

// 4. Handle installation completed
window.addEventListener('appinstalled', () => {
  deferredInstallPrompt = null;
  document.body.classList.add('running-as-app');
  const installBtn = document.getElementById('pwa-install-btn');
  if (installBtn) installBtn.style.display = 'none';
  closeInstallGuideModal();
  if (typeof triggerConfetti === 'function') triggerConfetti();
  if (typeof showToast === 'function') {
    showToast('AI Study Hub installed as app! Launch it anytime from your screen ??', 'success');
  }
});

// 5. User clicks "Install App" button in navbar
function triggerPwaInstall() {
  playSound('chime');
  
  if (deferredInstallPrompt) {
    executeNativeInstallPrompt();
  } else {
    // Open install guide modal with auto-selected tab based on user agent
    const modal = document.getElementById('install-guide-modal');
    if (modal) modal.style.display = 'flex';
    
    // Auto-select tab
    const ua = navigator.userAgent.toLowerCase();
    if (/android/.test(ua)) {
      switchInstallTab('android');
    } else if (/iphone|ipad|ipod/.test(ua)) {
      switchInstallTab('ios');
    } else {
      switchInstallTab('laptop');
    }
  }
}

// 6. Execute native browser install prompt
async function executeNativeInstallPrompt() {
  if (deferredInstallPrompt) {
    deferredInstallPrompt.prompt();
    const { outcome } = await deferredInstallPrompt.userChoice;
    console.log('Install prompt user choice:', outcome);
    deferredInstallPrompt = null;
    closeInstallGuideModal();
    if (outcome === 'accepted') {
      if (typeof showToast === 'function') {
        showToast('Installing AI Study Hub...', 'info');
      }
    }
  } else {
    if (typeof showToast === 'function') {
      showToast('Follow the steps on screen or look for the Install icon in your address bar ??', 'info');
    }
  }
}

// 7. Switch Install Modal Platform Tabs
function switchInstallTab(platform) {
  playSound('click');
  document.querySelectorAll('.platform-tab').forEach((tab) => {
    tab.classList.toggle('active', tab.id === `tab-btn-${platform}`);
  });
  document.querySelectorAll('.platform-pane').forEach((pane) => {
    pane.classList.toggle('active', pane.id === `pane-install-${platform}`);
  });
}

function closeInstallGuideModal() {
  const modal = document.getElementById('install-guide-modal');
  if (modal) modal.style.display = 'none';
}

