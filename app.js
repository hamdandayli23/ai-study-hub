function renderProgressTab() {
  const masteryPctEl = document.getElementById("progress-mastery-pct");
  const masteryCircle = document.getElementById("progress-mastery-circle");
  const studyTimeEl = document.getElementById("progress-study-time");
  const quizzesValEl = document.getElementById("progress-quizzes-val");
  const avgAccuracyEl = document.getElementById("progress-avg-accuracy");
  const streakValEl = document.getElementById("progress-streak-val");

  // Calculate average mastery from topics
  const avgMastery = Math.round(
    userStats.masteryTopics.reduce((acc, t) => acc + t.mastery, 0) / userStats.masteryTopics.length
  );

  if (masteryPctEl) masteryPctEl.textContent = `${avgMastery}%`;
  if (masteryCircle) {
    const offset = 377 - (377 * avgMastery) / 100;
    setTimeout(() => {
      masteryCircle.style.strokeDashoffset = offset;
    }, 150);
  }

  const hours = Math.floor(userStats.studyMinutes / 60);
  const mins = userStats.studyMinutes % 60;
  if (studyTimeEl) studyTimeEl.textContent = `${hours}h ${mins}m`;
  if (quizzesValEl) quizzesValEl.textContent = `${userStats.quizzesSolved} Solved`;
  if (avgAccuracyEl) avgAccuracyEl.textContent = `${userStats.averageScore}%`;
  if (streakValEl) streakValEl.textContent = `${userStats.streak} Days`;

  // Render 28-day Activity Heatmap
  renderHeatmap();

  // Render Topic Mastery list
  renderTopicMastery();

  // Render Quiz History list
  renderQuizHistory();

  // Render Achievements
  renderAchievements();
}

