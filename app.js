function confirmDeleteDocument(packId) {
  const pack = STUDY_PACKS[packId];
  if (!pack) return;
  packToDeleteId = packId;
  playSound("click");

  const titleEl = document.getElementById("delete-modal-doc-title");
  if (titleEl) titleEl.textContent = pack.title;

  const modal = document.getElementById("delete-doc-modal");
  if (modal) modal.style.display = "flex";
}

function closeDeleteModal() {
  playSound("click");
  packToDeleteId = null;
  const modal = document.getElementById("delete-doc-modal");
  if (modal) modal.style.display = "none";
}

function executeDeleteDocument() {
  if (!packToDeleteId || !STUDY_PACKS[packToDeleteId]) {
    closeDeleteModal();
    return;
  }

  const deletedTitle = STUDY_PACKS[packToDeleteId].title;
  delete STUDY_PACKS[packToDeleteId];

  // Remove related mastery topics
  if (userStats.masteryTopics) {
    userStats.masteryTopics = userStats.masteryTopics.filter((t) => t.packId !== packToDeleteId);
  }

  // Update document counter
  userStats.docsCount = Object.keys(STUDY_PACKS).length;

  const remainingKeys = Object.keys(STUDY_PACKS);
  if (remainingKeys.length === 0) {
    // If all documents were deleted, recreate a fresh study pack
    const freshPack = generateDynamicStudyPack("New_Study_Lecture.pdf");
    STUDY_PACKS[freshPack.id] = freshPack;
    currentPackId = freshPack.id;
    loadStudyPack(currentPackId);
  } else {
    if (currentPackId === packToDeleteId) {
      currentPackId = remainingKeys[0];
      loadStudyPack(currentPackId);
    }
  }

  populateDocSelector();
  saveUserStats();
  renderLibraryModalItems();
  closeDeleteModal();

  playSound("click");
  showToast(`🗑️ "${deletedTitle}" was deleted from your workspace.`, "info");
}

function populateDocSelector() {
  const selector = document.getElementById("doc-selector");
  if (!selector) return;

  selector.innerHTML = Object.keys(STUDY_PACKS).map((key) => {
    const pack = STUDY_PACKS[key];
    return `<option value="${key}">${pack.title}</option>`;
  }).join("");

  selector.value = currentPackId;
}

